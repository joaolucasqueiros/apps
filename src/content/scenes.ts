import type { Exercise, Word } from "../types";
export type SceneId =
  | "body"
  | "house"
  | "car"
  | "traffic"
  | "restaurant"
  | "everyday";
export interface SceneItem {
  id: string;
  en: string;
  pt: string;
  example: string;
  translation: string;
  x: number;
  y: number;
}
export interface Scene {
  id: SceneId;
  title: string;
  subtitle: string;
  icon: string;
  level: "A1" | "A2";
  lesson: string;
  items: SceneItem[];
}
type Item = [string, string, string, string, number, number];
const create = (
  id: SceneId,
  title: string,
  subtitle: string,
  icon: string,
  level: "A1" | "A2",
  lesson: string,
  rows: Item[],
): Scene => ({
  id,
  title,
  subtitle,
  icon,
  level,
  lesson,
  items: rows.map(([en, pt, example, translation, x, y]) => ({
    id: `scene-${id}-${en.replace(/[^a-z]+/g, "-")}`,
    en,
    pt,
    example,
    translation,
    x,
    y,
  })),
});
